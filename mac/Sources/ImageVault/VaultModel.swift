import AppKit

extension Notification.Name {
    static let vaultChanged = Notification.Name("ImageVault.vaultChanged")
}

/// UI-side view of the vault. Reloads when the index file changes on disk,
/// which covers writes from this app and from the Chrome bridge process.
@MainActor
final class VaultModel {
    static let shared = VaultModel()

    private(set) var items: [VaultItem] = []
    private(set) var byID: [String: VaultItem] = [:]
    private(set) var groups: [VaultGroup] = []
    /// Item id → the folder it lives in.
    private(set) var groupOf: [String: String] = [:]
    /// Ids added since the last reload, so tiles can play their entrance.
    private(set) var fresh: Set<String> = []
    private var lastModified: Date?
    private var timer: Timer?

    func start() {
        reload()
        timer = Timer.scheduledTimer(withTimeInterval: 1.0, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.reloadIfChanged() }
        }
    }

    func reloadIfChanged() {
        let modified = VaultStore.shared.indexModified
        if modified != lastModified { reload() }
    }

    func reload(fresh newIDs: Set<String> = []) {
        lastModified = VaultStore.shared.indexModified
        let old = Set(items.map(\.id))
        var seen = Set<String>()
        let index = VaultStore.shared.load()
        let next = index.items.filter { seen.insert($0.id).inserted }
        groups = index.groups ?? []
        groupOf = [:]
        for g in groups { for id in g.itemIDs where groupOf[id] == nil { groupOf[id] = g.id } }
        items = next
        // Never trap on a duplicate id in a hand-edited / half-synced index.
        byID = Dictionary(next.map { ($0.id, $0) }, uniquingKeysWith: { first, _ in first })
        // Items that appeared from elsewhere (Chrome sync) also get the entrance.
        fresh = newIDs.union(old.isEmpty ? [] : Set(next.map(\.id)).subtracting(old))
        NotificationCenter.default.post(name: .vaultChanged, object: nil)
    }

    // MARK: Delete with undo

    private var undoStack: [(token: UUID, items: [VaultItem])] = []

    func delete(ids: [String]) {
        let removed = VaultStore.shared.delete(ids: ids)
        guard !removed.isEmpty else { return }
        let token = UUID()
        undoStack.append((token, removed))
        if undoStack.count > 20 { undoStack.removeFirst() }
        reload()
        // Files stay for the undo window, then go. Taking the batch off the
        // undo stack at the same time keeps the window honest and means files
        // (and the undo stack) can't accumulate for the life of the process.
        DispatchQueue.main.asyncAfter(deadline: .now() + 60) { [weak self] in
            guard let self else { return }
            self.undoStack.removeAll { $0.token == token }
            let keep = Set(self.undoStack.flatMap { $0.items.map(\.id) })
            VaultStore.shared.purgeFiles(removed.filter { !keep.contains($0.id) })
        }
    }

    @discardableResult
    func undoDelete() -> Int {
        guard let last = undoStack.popLast() else { return 0 }
        VaultStore.shared.restore(last.items)
        reload()
        return last.items.count
    }
}

/// Saves every image copied anywhere on the Mac (not files, not our own copies,
/// not password-manager / transient content).
@MainActor
final class ClipboardWatcher {
    private var changeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    var onSaved: ((Ingest.Summary) -> Void)?

    private let skipTypes: [NSPasteboard.PasteboardType] = [
        Clipboard.marker, .fileURL,
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    var enabled: Bool {
        get { UserDefaults.standard.object(forKey: "saveClipboard") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "saveClipboard") }
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        let types = pb.types ?? []
        // History gets everything except our own writes and secrets; the vault
        // only gets images, and only when "Save Copied Images" is on.
        let secret = types.contains(where: skipTypes.dropFirst(2).contains)
        if !secret, !types.contains(Clipboard.marker) { ClipboardHistory.shared.record(pb) }
        guard enabled else { return }
        if types.contains(where: skipTypes.contains) { return }
        guard let type = Ingest.preferredDataOrder.first(where: types.contains), let data = pb.data(forType: type) else { return }
        let candidate = Ingest.Candidate(data: data, name: nil, url: pb.string(forType: .URL))
        Task { [weak self] in
            let summary = await Ingest.saveAsync([candidate], source: "clipboard")
            if !summary.added.isEmpty { self?.onSaved?(summary) }
        }
    }
}

/// Imports new screenshots (Spotlight's kMDItemIsScreenCapture), wherever
/// the user saves them.
@MainActor
final class ScreenshotWatcher {
    private let query = NSMetadataQuery()
    private let launched = Date()
    private var seen = Set<String>()
    var onSaved: ((Ingest.Summary) -> Void)?

    var enabled: Bool {
        get { UserDefaults.standard.object(forKey: "saveScreenshots") as? Bool ?? true }
        set { UserDefaults.standard.set(newValue, forKey: "saveScreenshots") }
    }

    func start() {
        query.predicate = NSPredicate(format: "kMDItemIsScreenCapture = 1")
        query.searchScopes = [NSMetadataQueryUserHomeScope]
        NotificationCenter.default.addObserver(forName: .NSMetadataQueryDidUpdate, object: query, queue: .main) { [weak self] note in
            let added = note.userInfo?[NSMetadataQueryUpdateAddedItemsKey] as? [NSMetadataItem] ?? []
            MainActor.assumeIsolated { self?.handle(added) }
        }
        query.start()
    }

    private func handle(_ added: [NSMetadataItem]) {
        guard enabled else { return }
        for item in added {
            guard let path = item.value(forAttribute: NSMetadataItemPathKey) as? String, !seen.contains(path) else { continue }
            let created = item.value(forAttribute: NSMetadataItemFSCreationDateKey) as? Date ?? .distantPast
            guard created > launched else { continue }
            seen.insert(path)
            // Give screencapture a moment to finish writing the file.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.6) { [weak self] in
                let url = URL(fileURLWithPath: path)
                Task { [weak self] in
                    let data = await Task.detached(priority: .utility) {
                        try? Data(contentsOf: url)
                    }.value
                    guard let data else { return }
                    let summary = await Ingest.saveAsync(
                        [Ingest.Candidate(data: data, name: url.lastPathComponent, url: nil)],
                        source: "screenshot")
                    if !summary.added.isEmpty { self?.onSaved?(summary) }
                }
            }
        }
    }
}
